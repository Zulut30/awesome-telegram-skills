"""Generate packages/typescript/src/native-signatures.ts: typed arguments and results of the native Mini App methods.

    python scripts/build_native_signatures.py           # write the module
    python scripts/build_native_signatures.py --check   # fail when it is stale

Parameter names and optionality come from the official signatures in catalog/mini-app-index.json
(`start(params[, callback])`); types come from the documentation table catalog/mini-app-types.json. The generator
refuses a table whose methods or parameters differ from the official signatures, so a documentation update cannot
leave a stale or invented parameter behind.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INDEX = ROOT / 'catalog/mini-app-index.json'
TYPES = ROOT / 'catalog/mini-app-types.json'
OUTPUT = ROOT / 'packages/typescript/src/native-signatures.ts'


def official_parameters(signature: str) -> list[tuple[str, bool]]:
    """(name, optional) pairs of an official signature such as `setEmojiStatus(custom_emoji_id[, params, callback])`."""
    inner = signature[signature.index('(') + 1 : signature.rindex(')')]
    result: list[tuple[str, bool]] = []
    depth, name, optional = 0, '', False
    for char in inner + ',':
        if char == '[':
            depth += 1
        elif char == ']':
            depth -= 1
        elif char == ',':
            if name:
                result.append((name, optional))
            name = ''
        elif not char.isspace():
            if not name:
                optional = depth > 0  # a parameter is optional when it starts inside brackets
            name += char
    if depth:
        raise ValueError(f'Unbalanced brackets in {signature}')
    return result


def overload_arguments(path: str, declared: list[tuple[str, str]], expected: list[tuple[str, bool]], overloads: object) -> str:
    """Explicit SDK-reviewed optional-argument shifts, retaining the complete official branch."""
    names = [name for name, _ in declared]
    kinds, optional = dict(declared), dict(expected)
    required = {name for name, is_optional in expected if not is_optional}
    if not isinstance(overloads, list) or len(overloads) < 2:
        raise ValueError(f'{path}: overloads need at least two reviewed branches')
    branches = []
    for branch in overloads:
        if (not isinstance(branch, list) or any(not isinstance(name, str) for name in branch)
                or len(set(branch)) != len(branch) or not set(branch).issubset(names)
                or not required.issubset(branch) or [name for name in names if name in branch] != branch):
            raise ValueError(f'{path}: overload parameters must retain required names and official order')
        branches.append('[' + ', '.join(f"{name}{'?' if optional[name] else ''}: {kinds[name]}" for name in branch) + ']')
    if names not in overloads or len(set(branches)) != len(branches):
        raise ValueError(f'{path}: overloads need distinct branches and the full official parameters')
    return '...args: ' + ' | '.join(branches)


def render(index: dict, table: dict) -> str:
    official = {item['path']: official_parameters(item['signature']) for item in index['methods']}
    methods = table['methods']
    if set(methods) != set(official):
        missing, extra = sorted(set(official) - set(methods)), sorted(set(methods) - set(official))
        raise ValueError(f'Type table differs from the official methods: missing {missing}, extra {extra}')
    field_types = {'String': 'string', 'Integer': 'number', 'Float': 'number', 'Boolean': 'boolean',
                   'Object': 'Readonly<Record<string, unknown>>'}
    def compact(text: str) -> str:
        return re.sub(r'\s+', '', text)
    for item in index['methods']:
        if not item.get('callback_error'): continue
        name = methods[item['path']].get('callback_error_declaration')
        declaration = table['declarations'].get(name, '')
        expected_fields = []
        for field, shape in item['callback_error'].items():
            if shape['type'] not in field_types:
                raise ValueError(f"{item['path']}: review unknown callback error field type {shape['type']}")
            expected_fields.append(f"readonly {field}{'?' if shape['optional'] else ''}: {field_types[shape['type']]}")
        actual = {compact(part) for part in declaration.removeprefix('{').removesuffix('}').split(';') if part.strip()}
        if not declaration.startswith('{') or not declaration.endswith('}') or actual != {compact(part) for part in expected_fields}:
            raise ValueError(f"{item['path']}: callback error declaration differs from the official fields")
    lines = [
        '// Generated by scripts/build_native_signatures.py. Do not edit: change catalog/mini-app-types.json.',
        '// Parameter names and optionality follow the official signatures (catalog/mini-app-index.json);',
        f"// types follow {table['source']} (checked {table['checked_date']}).",
        "import type {TelegramNativeEvent, TelegramNativeMethod} from './native-catalog.js';",
        '',
    ]
    for review in table.get('partial_reviews', []):
        lines.append(f"// Partial review {review['checked_date']}: {', '.join(review['methods'])}; other types retain their prior review.")
    for name, value in table['declarations'].items():
        keyword = 'interface' if value.startswith('{') and '<' not in name else 'type'
        lines.append(f'export interface {name} {value}' if keyword == 'interface' else f'export type {name} = {value};')
    lines += ['', '/** Documented arguments and result of every native method, keyed by its path. */',
              'export interface TelegramNativeSignatures {']
    for path in sorted(methods):
        declared = list(methods[path]['parameters'].items())
        expected = official[path]
        if [name for name, _ in declared] != [name for name, _ in expected]:
            raise ValueError(f'{path}: parameters {[n for n, _ in declared]} differ from the official {expected}')
        arguments = (overload_arguments(path, declared, expected, methods[path]['overloads'])
                     if 'overloads' in methods[path] else ', '.join(f"{name}{'?' if optional else ''}: {kind}"
                                                                  for (name, kind), (_, optional) in zip(declared, expected)))
        lines.append(f"  '{path}': ({arguments}) => {methods[path]['returns']};")
    lines += [
        '}',
        '',
        'type Exact<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false;',
        'type Assert<T extends true> = T;',
        '/** Compile-time proof that every catalog method has exactly one signature. */',
        'export type TelegramNativeSignaturesComplete = Assert<Exact<keyof TelegramNativeSignatures, TelegramNativeMethod>>;',
        'export type TelegramNativeArguments<P extends TelegramNativeMethod> = Parameters<TelegramNativeSignatures[P]>;',
        'export type TelegramNativeResult<P extends TelegramNativeMethod> = ReturnType<TelegramNativeSignatures[P]>;',
        '',
    ]
    return '\n'.join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='fail instead of writing when the module is stale')
    args = parser.parse_args()
    content = render(json.loads(INDEX.read_text(encoding='utf-8')), json.loads(TYPES.read_text(encoding='utf-8')))
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding='utf-8') != content:
            sys.stderr.write(f'{OUTPUT.relative_to(ROOT)} is stale; run python scripts/build_native_signatures.py\n')
            return 1
    else:
        OUTPUT.write_text(content, encoding='utf-8', newline='\n')
    print(json.dumps({'passed': True, 'methods': len(json.loads(TYPES.read_text(encoding='utf-8'))['methods']),
                      'check': args.check}))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
